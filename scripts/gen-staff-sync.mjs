// Regenerates supabase/002-staff-sync.sql from timetable/dott-baseline.json.
// Run after a timetable change: node scripts/gen-staff-sync.mjs
// Then paste the SQL into the Supabase SQL Editor (safe to re-run: it
// upserts on hub_key and never deletes).
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const baseline = JSON.parse(readFileSync(path.join(root, 'timetable', 'dott-baseline.json'), 'utf8'))

const typeOf = (g) => (g === 'specialist' ? 'specialist' : 'classroom')
const esc = (s) => String(s).replace(/'/g, "''")

const rows = baseline.staff.map((s) =>
  `  ('${esc(s.name)}', '${typeOf(s.group)}', ${s.fte.toFixed(2)}, '${esc(s.key)}', '${esc(s.label)}')`
)

const sql = `-- Staff registry sync (generated by scripts/gen-staff-sync.mjs — do not hand-edit)
-- Source: timetable/dott-baseline.json built ${baseline.meta.baselineBuilt}
-- Safe to re-run after every timetable change: upserts on hub_key, never deletes.

alter table public.staff add column if not exists hub_key text unique;

insert into public.staff (full_name, staff_type, fte, hub_key, notes) values
${rows.join(',\n')}
on conflict (hub_key) do update set
  full_name  = excluded.full_name,
  staff_type = excluded.staff_type,
  fte        = excluded.fte,
  notes      = excluded.notes,
  active     = true,
  updated_at = now();
`

writeFileSync(path.join(root, 'supabase', '002-staff-sync.sql'), sql)
console.log(`Wrote supabase/002-staff-sync.sql (${rows.length} staff)`)
